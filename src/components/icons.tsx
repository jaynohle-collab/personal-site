export function SocialIcon({
  label,
  className,
}: {
  label: string;
  className?: string;
}) {
  switch (label.toLowerCase()) {
    case "github":
      return <GitHubIcon className={className} />;
    case "linkedin":
      return <LinkedInIcon className={className} />;
    case "email":
    case "mail":
      return <EmailIcon className={className} />;
    default:
      return <LinkIcon className={className} />;
  }
}
